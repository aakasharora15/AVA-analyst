// Writes supabase/seed.sql: the demo portfolio from src/data/mock as one
// organisation ('demo-fund'), for staging and walkthroughs. Never run it on
// a production project with real clients.
//
//   node scripts/generate-seed.mjs
//
// Members are not seeded (they need real Supabase Auth accounts). After you
// sign up, make yourself the demo Owner with the statement at the end of the file.

import { readFileSync, writeFileSync } from 'node:fs';

const load = (f) => JSON.parse(readFileSync(new URL(`../src/data/mock/${f}.json`, import.meta.url), 'utf8'));
const companies = load('companies');
const audits = load('audits');
const sources = load('sources');
const alerts = load('alerts');
const outcomes = load('outcomes');
const org = load('org');
const log = load('audit-log');
const ORG = 'demo-fund';

// text[] columns; every other array or object is jsonb.
const TEXT_ARRAYS = new Set(['override_cited', 'source_ids', 'sources', 'anchoring_finding_ids']);
const q = (v, col = '') => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number') return String(v);
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (TEXT_ARRAYS.has(col)) return v.length ? `array[${v.map((x) => q(x)).join(', ')}]::text[]` : `'{}'::text[]`;
  if (typeof v === 'object') return `${q(JSON.stringify(v))}::jsonb`;
  return `'${String(v).replaceAll("'", "''")}'`;
};
const insert = (table, row) => `insert into public.${table} (${Object.keys(row).join(', ')}) values (${Object.entries(row).map(([k, v]) => q(v, k)).join(', ')});`;
const out = [
  '-- Generated by scripts/generate-seed.mjs from src/data/mock. Demo data only.',
  'begin;',
  `delete from public.organisations where id = ${q(ORG)};`,
  insert('organisations', { id: ORG, name: org.name, kind: org.kind, plan: org.plan, branding: org.branding, alert_rules: org.alertRules, delivery: org.delivery, default_cadence: org.cadence, currency: org.currency, storage_region: org.region }),
];

for (const c of companies) {
  out.push(insert('companies', {
    id: c.id, org_id: ORG, title: c.title, description: c.description, industry: c.industry, country: c.country, city: c.city, model: c.model, target: c.target,
    type: c.type, deal_lead: c.dealLead, stage: c.stage, fund: c.fund, budget: c.budget || '', extra: { delivery: c.delivery || '', price: c.price || '', competitors: c.competitors || '' },
    cadence: { mode: c.cadence.mode, paused: c.cadence.paused, resumeOn: c.cadence.resumeOn }, next_run: c.cadence.nextRun, coverage: c.coverage, open_items: c.openItems || [],
  }));
}
for (const s of sources) {
  out.push(insert('sources', {
    id: s.id, org_id: ORG, company_id: s.companyId, type: s.type, title: s.title, kind: s.kind, date: s.date, reliability: s.reliability, note: s.note,
    url: s.url || null, retrieval_date: s.type === 'public' ? (s.retrieved || s.date) : null, added_by: s.addedBy || '', status: 'read', extract: s.note,
  }));
}
for (const a of audits) {
  out.push(insert('audits', {
    id: a.id, org_id: ORG, company_id: a.companyId, date: a.date, status: a.status, trigger: a.trigger === 'shadow' ? 'manual' : a.trigger,
    score: a.score, raw_score: a.raw ?? null, exposure: a.exposure || null, cap: a.cap || null, base_directive: a.baseDirective, final_directive: a.finalDirective,
    overridden: !!a.overridden, override: a.override || null, override_cited: a.overrideCited || [], override_rejected: a.overrideRejected || null,
    coverage: a.coverage || null, skipped_sections: a.skippedSections || [], orchestrator: a.orchestrator || null, model_version: a.modelVersion, prompt_version: a.promptVersion,
    calibration_version: a.calibrationVersion, snapshot_hash: a.snapshotHash, source_ids: a.sourceIds || [], drift_flag: !!a.driftFlag, under_review: !!a.underReview,
    counted_against_usage: a.countedAgainstUsage !== false, first_checkpoint: a.firstCheckpoint || null, final_checkpoint: a.finalCheckpoint || null,
    outcome_window_version: a.outcomeWindowVersion || null, run_seconds: a.runSeconds || null,
  }));
  for (const r of a.agentRuns || []) {
    out.push(insert('agent_runs', { audit_id: a.id, org_id: ORG, agent: r.agent, status: r.status, duration_s: r.duration ?? null, retry_count: r.retries || 0, error_reason: r.error || null, schema_result: ['valid', 'malformed'].includes(r.schema) ? r.schema : null }));
  }
  a.findings.forEach((f, i) => {
    out.push(insert('findings', {
      id: f.id, audit_id: a.id, org_id: ORG, company_id: a.companyId, agent: f.agent, section: f.section, category: f.category, severity: f.severity, topic: f.topic,
      match_key: f.matchKey, title: f.title, text: f.text, sources: f.sources, status: f.status, owner: f.owner, dismiss_reason: f.dismissReason, history: f.history, position: i,
    }));
  });
}
for (const al of alerts) {
  out.push(insert('alerts', {
    id: al.id, org_id: ORG, company_id: al.companyId, audit_id: al.auditId, previous_audit_id: al.previousAuditId || null, trigger: al.trigger,
    from_score: al.fromScore ?? null, to_score: al.toScore ?? null, from_directive: al.fromDirective || null, to_directive: al.toDirective || null,
    caused_by_override: !!al.causedByOverride, anchoring_finding_ids: al.anchoringFindingIds || [], finding_id: al.findingId || null, detail: al.detail || null, date: al.date, emailed_at: al.emailedAt || null,
  }));
}
for (const o of outcomes) {
  out.push(insert('outcomes', { audit_id: o.auditId, org_id: ORG, result: o.result, checkpoint: o.checkpoint, outcome_date: o.date, evidence: o.evidence, logged_by: o.loggedBy, logged_at: o.loggedAt }));
}
for (const e of log) {
  out.push(insert('audit_log', { org_id: ORG, at: e.at, who: e.who, action: e.action, object_type: e.object, object_id: e.objectId, detail: e.detail }));
}
out.push('commit;', '',
  '-- Make yourself the demo Owner after signing up (replace the email):',
  "-- insert into public.profiles (user_id, email) select id, email from auth.users where email = 'you@yourfund.example' on conflict do nothing;",
  "-- insert into public.memberships (org_id, user_id, role) select 'demo-fund', id, 'Owner' from auth.users where email = 'you@yourfund.example';", '');
writeFileSync(new URL('../supabase/seed.sql', import.meta.url), out.join('\n'));
console.log(`supabase/seed.sql: ${companies.length} companies, ${audits.length} audits, ${audits.reduce((n, a) => n + a.findings.length, 0)} findings`);
